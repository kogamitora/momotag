export function detectLocale(): Locale {
  const language = (navigator.languages?.[0] ?? navigator.language ?? "en").toLowerCase();
  if (language.startsWith("ja")) return "ja";
  if (language.startsWith("zh")) return "zh";
  return "en";
}
